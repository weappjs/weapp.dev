import { Buffer } from 'node:buffer'
import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

// Developer tool only: reuse the application's installed image tooling.
const require = createRequire(new URL('../apps/web/package.json', import.meta.url))
const sharp = require('sharp')

const brandPath = new URL('../packages/site-ui/src/lib/hero-brand.ts', import.meta.url)
const outputPath = new URL('../packages/site-ui/src/scripts/hero-logo-data.ts', import.meta.url)
const source = await readFile(brandPath, 'utf8')
const path = source.match(/MINIPROGRAM_PATH = '([^']+)'/)?.[1]
if (!path) {
  throw new Error('The shared mini-program SVG path was not found')
}
const dimension = 1024
const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${dimension}" height="${dimension}" viewBox="0 0 ${dimension} ${dimension}"><path fill="white" fill-rule="evenodd" d="${path}"/></svg>`
const { data, info } = await sharp(Buffer.from(svg)).ensureAlpha().raw().toBuffer({ resolveWithObject: true })
if (info.channels !== 4) {
  throw new Error('Logo rasterization must provide an RGBA alpha mask')
}
let seed = 0x10C0517A
function next() {
  seed = seed + 0x6D2B79F5 | 0
  let t = Math.imul(seed ^ seed >>> 15, 1 | seed)
  t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t
  return ((t ^ t >>> 14) >>> 0) / 4294967296
}
const points = []
const used = new Set()
const pointSizes = [0.007, 0.009, 0.012]
const separation = 0.5
const bucketSize = 13
const bucketColumns = Math.ceil(dimension / bucketSize)
const buckets = new Map()
// Seven viewBox pixels leave room for every source star's largest radius.
function inside(x, y) {
  if (x < 7 || y < 7 || x >= dimension - 7 || y >= dimension - 7) {
    return false
  }
  for (let dy = -7; dy <= 7; dy += 1) {
    for (let dx = -7; dx <= 7; dx += 1) {
      if (data[((y + dy) * dimension + x + dx) * 4 + 3] < 200) {
        return false
      }
    }
  }
  return true
}
function overlaps(x, y, radius) {
  const column = Math.floor(x / bucketSize)
  const row = Math.floor(y / bucketSize)
  // The largest required center distance is 12.788, below one bucket's width.
  for (let dy = -1; dy <= 1; dy += 1) {
    for (let dx = -1; dx <= 1; dx += 1) {
      const neighbors = buckets.get((row + dy) * bucketColumns + column + dx) ?? []
      for (const neighbor of neighbors) {
        const distance = radius + neighbor.radius + separation
        if ((x - neighbor.x) ** 2 + (y - neighbor.y) ** 2 < distance ** 2) {
          return true
        }
      }
    }
  }
  return false
}
let attempts = 0
while (points.length < 2400) {
  attempts += 1
  if (attempts > 2_000_000) {
    throw new Error(`Safe non-overlapping Logo sampling stalled at ${points.length} of 2400 points`)
  }
  const x = Math.floor(next() * dimension)
  const y = Math.floor(next() * dimension)
  const key = y * dimension + x
  if (used.has(key) || !inside(x, y)) {
    continue
  }
  const packedX = Math.round((x + 0.5) / dimension * 65535)
  const packedY = Math.round((y + 0.5) / dimension * 65535)
  const centerX = packedX / 65535 * dimension
  const centerY = packedY / 65535 * dimension
  const radius = pointSizes[points.length % pointSizes.length] * dimension / 2
  // Check the encoded centers, so quantization cannot consume the 0.5px gap.
  if (overlaps(centerX, centerY, radius)) {
    continue
  }
  used.add(key)
  points.push([packedX, packedY])
  const bucketKey = Math.floor(centerY / bucketSize) * bucketColumns + Math.floor(centerX / bucketSize)
  const bucket = buckets.get(bucketKey) ?? []
  bucket.push({ x: centerX, y: centerY, radius })
  buckets.set(bucketKey, bucket)
}
const packed = Buffer.alloc(points.length * 4)
points.forEach(([x, y], index) => {
  packed.writeUInt16LE(x, index * 4)
  packed.writeUInt16LE(y, index * 4 + 2)
})
const hash = createHash('sha256').update(path).digest('hex')
const generated = `// Generated by scripts/generate-hero-logo.mjs; do not edit by hand.\nexport const HERO_LOGO_PATH_SHA256 = '${hash}'\nexport const HERO_LOGO_POINT_SIZES = [${pointSizes.join(', ')}] as const\nexport const HERO_LOGO_COORDINATES = '${packed.toString('base64')}'\n`
if (process.argv.includes('--check')) {
  const existing = await readFile(outputPath, 'utf8')
  if (existing !== generated) {
    throw new Error('Particle Logo data is stale; run node scripts/generate-hero-logo.mjs')
  }
  process.stdout.write('Particle Logo data matches the shared SVG: 2400 safe non-overlapping points with a 0.5px gap, including the 900-point mobile prefix.\n')
}
else {
  await writeFile(outputPath, generated)
  process.stdout.write(`Generated ${points.length} particle Logo points: ${fileURLToPath(outputPath)}\n`)
}
